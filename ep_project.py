  day_data["delta_t"].fillna(0, inplace=True)
  day_data['Energy(J)']=day_data['power_kw']*day_data['delta_t']*1000
  day_data['Fuel_Consumed(l)']=day_data['fuel_lph']*(day_data['delta_t']/3600)
  return day_data


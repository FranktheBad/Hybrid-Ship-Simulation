def fuel_consumption(start_time, end_time, data):
  mask = (data["datetime"] >= start_time) & (data["datetime"] <= end_time)
  date_data = data.loc[mask]
  date_data["delta_t"] = date_data["datetime"].diff().dt.total_seconds()
  date_data["delta_t"].fillna(0, inplace=True)
  date_data['Fuel_Consumed(l)']=date_data['fuel_lph']*(date_data['delta_t']/3600)
  Total_fuel_consumed = date_data['Fuel_Consumed(l)'].sum()
  fuel_consumed_data=pd.DataFrame(columns=["start_time", "end_time",'tot_fuel_consumed(l)'])
  new_row = pd.DataFrame([{"start_time": start_time,"end_time": end_time, "tot_fuel-consumed(l)": Total_fuel_consumed}])
  fuel_consumed_data = pd.concat([fuel_consumed_data, new_row], ignore_index=True)

  return fuel_consumed_data


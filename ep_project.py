def calculate_tripEnerrgy(df1,df2,column_name):
  for i in range(len(df2)):
    start_time=df2['start_datetime'][i]
    end_time=df2['end_datetime'][i]
    mask = (df1["datetime"] >= start_time) & (df1["datetime"] <= end_time)
    df_filtered = df1.loc[mask]
    df_filtered["delta_t"] = df_filtered["datetime"].diff().dt.total_seconds()
    df_filtered["delta_t"].fillna(0, inplace=True)
    df_filtered['Energy(J)']=df_filtered['power_kw']*df_filtered['delta_t']*1000
    df2.loc[i,column_name]=df_filtered['Energy(J)'].sum()
  return df2

